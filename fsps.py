def read_mags(magfile, extinction=""):
    '''Reads in the raw magnitude file generated by FSPS.

    This function will read in the entries given in the mags file. The
    quantities which are not magnitudes will be given as base 10 logs in order
    to prevent over/underflows for some reason.

    The extinction flag will allow an extinction table to be used. Currently,
    the extinction table should be output in the form of an IPAC table from the
    IRSA Dust Extinction Service.
    '''
    # There may be a way to have the extinction pulled from the server. But
    # this will not be important in the short-term.
    magtable = Table.read(magfile, format="ascii.no_header")
    rename_mag_table(magtable)
    useful_table = filter_mag_table(magtable)
    return useful_table

def read_specs(specfile, extinction=""):
    '''Reads in the raw spectrum generated by FSPS.

    This function will read in all of the entries in the spec file. The first
    four columns will be the logarithm of the age, mass, bolometric luminosity,
    and star formation rate (with units of years, solar masses, solar
    luminosities, and solar masses per year, respectively). The columns
    afterward will be the spectra with the column name being a string
    representation of the wavelength in Angstroms. 

    Extinction may or may not be implemented at some later date.
    '''
    f = open(specfile, 'r')
    fullfile = f.readlines()
    specfile = fullfile[9::2]
    infofile = fullfile[10::2]

    spectable = Table.read(specfile, format="ascii.basic")
    infotable = Table.read(
        infofile, format="ascii.no_header", 
        names=("log(age)", "log(mass)", "log(lbol)", "log(SFR)"))

    fulltable = hstack([infotable, spectable])
    return fulltable

def rename_mag_table(magtable):
    '''Renames the columns from a just-read magnitude table.

    The magtable doesn't contain the names for the columns, so they will be put
    in post-hoc. Note that this changes the original table, it does not return
    a table.'''

    for column_name in magtable.colnames:
        colnum = strip_colnumber(column_name)
        if colnum == 1:
            newcolname = "log(age)"
        elif colnum == 2:
            newcolname = "log(mass)"
        elif colnum == 3:
            newcolname = "Log(lbol)"
        elif colnum == 4:
            newcolname = "log(SFR)"
        else:
            newcolname = "filter{0:d}".format(colnum-4)
        magtable.rename_column(column_name, newcolname)

def filter_mag_table(magtable):
    '''Filters the entries from the magnitude table that we want.

    These entries will namely be age, W1, W2, W3, W4, NUV, and FUV.
    '''
    newtable = Table([10**magtable["log(age)"], 10**magtable["log(SFR)"],
                      magtable["filter10"], magtable["filter11"], 
                      magtable["filter12"], magtable["filter83"], 
                      magtable["filter84"], magtable["filter85"], 
                      magtable["filter86"], magtable["filter62"], 
                      magtable["filter63"]], 
                     names=("Age", "SFR", 
                            "J", "H", "Ks", 
                            "W1", "W2", "W3", "W4", 
                            "FUV", "NUV"))
    return newtable


def strip_colnumber(col):
    '''Strips the column number from a default column name.

    All column names are named by col[X] where X is the column number starting
    with col1 and up to the number of columns. This function extracts X as an
    integer.
    '''
    return int(col[3:])

