def plot_atlas3d_coded_by_metallicity(xvalues, yvalues, yerrs, xerrs, ylims, zh, 
                                      zh_lim=0.0):
    '''Plots atlas3d points so that they are color-coded by metallicity.

    This function will ONLY plot points such that those with [Z/H] values as
    determined by SSP models higher than the provided zh value will be red,
    while those with lower metallicities will be blue. By default, zh
    corresponds to solar metallicity. The atlas3dtable will require a column
    named "z/h".
    '''
    highmetindices = np.where(zh >= zh_lim)
    lowmetindices = np.where(zh < zh_lim)
    highmetx, highmety = xvalues[highmetindices], yvalues[highmetindices]
    lowmetx, lowmety = xvalues[lowmetindices], yvalues[lowmetindices]
    highmetxerr, highmetyerr = xerrs[highmetindices], yerrs[highmetindices]
    lowmetxerr, lowmetyerr = xerrs[lowmetindices], yerrs[lowmetindices]
    highmetlims = ylims[highmetindices]
    lowmetlims = ylims[lowmetindices]
    
    stat.errorbar(highmetx, highmety, highmetyerr, highmetxerr, highmetlims, 
                  'r.', label="[Z/H] >= {0:.1f}".format(zh_lim), ufmt='rv', 
                  lfmt='r^')
    stat.errorbar(lowmetx, lowmety, lowmetyerr, lowmetxerr, lowmetlims, 'b.',
                  label="[Z/H] < {0:.1f}".format(zh_lim), ufmt='bv', lfmt='r^')


def color_difference_plot(times, outputdir=TBURST_PATH, prefix1="early_t",
                          colorsuff1="", prefix2="noagbdust_t",
                          colorsuff2=" (No dust)", title="Dust Difference", 
                          label="{0} Gyr", loc="upper right", 
                          bands=ALL_COLORS):
    '''Plots the color difference between two classes of models.

    Times should be a list of ages that should be evaluated in Gyr. Integer
    values between 1 and 15 are acceptable. outputdir is the directory where
    the files holding the output variation are located. The first prefix
    indicates the class of models which will be left of the subtraction sign
    (minuend), and the second prefix indicates the class which will be on the
    right (subtrahend). The colorsuffs are suffixes which will be printed
    after the colors on the y-axis label. For example, the default colorsuff
    will yield (W1-W2)-(W1-W2)_nodust. The bands keyword should be a list of
    tuples representing the color of the band. For an explicit example, see the
    ALL_COLORS constant in this file.

    The title will be the title of the plot. Label will be formatted to have
    the current value in the time array as the first argument. Loc will be
    passed to the legend command to place the legend.'''
    for  blueband, redband in bands:
        plt.figure()
        for i, t in enumerate(times):
            topfile = os.path.join(outputdir, 
                                    "{0}{1:02d}.mags".format(prefix1, t))
            toptable = read_mags(topfile)
            bottomfile = os.path.join(outputdir, 
                                    "{0}{1:02d}.mags".format(prefix2, t))
            bottomtable = read_mags(bottomfile)

            if not np.array_equal(bottomtable["Age"], toptable["Age"]):
                raise ValueError("FSPS model ages do not match!")
            else:
                ages = bottomtable["Age"]
            topcolor = toptable[blueband] - toptable[redband]
            bottomcolor = bottomtable[blueband] - bottomtable[redband]
            colordiff = topcolor - bottomcolor
            linecolor = plt.rcParams["axes.color_cycle"][i]
            plt.plot(ages/1e9, topcolor, '-', label=label.format(t)+colorsuff1,
                     color=linecolor)
            plt.plot(ages/1e9, bottomcolor, ':',
                     label=label.format(t)+colorsuff2,
                     color=linecolor)
            plt.title(title)
            plt.xlabel("Age (Gyr)")
            plt.ylabel("({0}-{1})".format(blueband, redband))
            plt.legend(loc=loc)

def Astropy_Table_to_numpy_array(table, dtype=np.float64):
    '''Converts an Astropy table to a 2-D numpy array.

    NOTE: This requires all of the entries in the table to be of the given
    dtype.
    '''
    data = np.ma.array(table)
    arr = data.view(dtype).reshape(len(data), len(data.dtype))
    return arr

def mag_table_to_flux_table(
    table, runbands=(conv.WISE_bands + conv.TWOMASS_bands + conv.GALEX_bands),
    ZP="AB"):
    '''Converts a table in magnitudes to a table in fluxes.'''
    mag_columns = [phot.name_photometry_column(band, error=False) for band in
                   runbands]
    err_columns = [phot.name_photometry_column(band, error=True) for band in
                   runbands]
    newtable = table[["objstr_01"]]
    for band in runbands:
        mag_column = phot.name_photometry_column(band, error=False)
        err_column = phot.name_photometry_column(band, error=True)
        if ZP is "AB":
            newtable[mag_column] = conv.ABmag2Jansky(band, table[mag_column])
        elif ZP is "Vega":
            newtable[mag_column] = conv.Vegamag2Jansky(band, table[mag_column])
        else:
            raise ValueError("Don't understand magnitude system: "
                             "{0}.".format(ZP))
        newtable[err_column] = conv.Mag_err_to_Jansky_err(
            band, table[mag_column], table[err_column])
    return newtable

